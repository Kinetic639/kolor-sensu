#!/bin/bash
# Writes each app's .env.local from prefixed environment variables.
#
# Cloud sessions keep every variable in one environment shared by the whole
# monorepo, so each name carries a prefix that says where it belongs. This
# script strips the prefix and writes the variable to the right files:
#
#   SHARED__X      -> apps/web, apps/admin, apps/specialist (and the root)
#   WEB__X         -> apps/web
#   ADMIN__X       -> apps/admin
#   SPECIALIST__X  -> apps/specialist
#   ROOT__X        -> the root .env.local (read by Playwright)
#
# E2E_* and UI_DEMO_* variables (test accounts) also go to the root
# .env.local, whatever their prefix, because the e2e tests run from there.
#
# Fallbacks, only when the app's own name is not set:
#   NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY <- SUPABASE_TARGET_PUBLISHABLE_KEY
#                                           or NEXT_PUBLIC_SUPABASE_ANON_KEY
#   NEXT_PUBLIC_SUPABASE_URL             <- SUPABASE_TARGET_URL
#   NEXT_PUBLIC_WEB_URL / _ADMIN_URL / _SPECIALIST_URL <- localhost:3000/1/2
#
# A .env.local this script did not write (no header line) is left alone.
# The files are gitignored; values never leave the machine.
set -euo pipefail

root="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
header="# Generated by scripts/sync-env.sh from prefixed environment variables. Do not edit: changes are overwritten."

declare -A files=(
  [web]="$root/apps/web/.env.local"
  [admin]="$root/apps/admin/.env.local"
  [specialist]="$root/apps/specialist/.env.local"
  [root]="$root/.env.local"
)
declare -A content=()

# Quote a value for @next/env (dotenv + dotenv-expand). Quotes are taken
# literally inside the other kind, and "$" is escaped so dotenv-expand does
# not read it as a variable reference.
quote() {
  local v="${1//\$/\\\$}"
  if [[ $v != *"'"* ]]; then
    printf "'%s'" "$v"
  elif [[ $v != *'"'* && $v != *'\n'* && $v != *'\r'* ]]; then
    # dotenv turns \n and \r into line breaks inside double quotes only.
    printf '"%s"' "$v"
  else
    printf '`%s`' "$v"
  fi
}

add() { # target name value
  local line
  line="$2=$(quote "$3")"
  case $'\n'"${content[$1]:-}" in
    *$'\n'"$2="*) return ;; # first definition wins
  esac
  content[$1]+="$line"$'\n'
}

has() { # target name
  case $'\n'"${content[$1]:-}" in *$'\n'"$2="*) return 0 ;; esac
  return 1
}

found=0
# App-specific prefixes first so they win over SHARED__ for the same name.
for prefix in WEB ADMIN SPECIALIST ROOT SHARED; do
  while IFS= read -r name; do
    key="${name#"${prefix}"__}"
    [ -n "$key" ] || continue
    value="${!name}"
    found=1
    case $prefix in
      WEB) targets=(web) ;;
      ADMIN) targets=(admin) ;;
      SPECIALIST) targets=(specialist) ;;
      ROOT) targets=(root) ;;
      SHARED) targets=(web admin specialist root) ;;
    esac
    case $key in E2E_* | UI_DEMO_*) targets+=(root) ;; esac
    for t in "${targets[@]}"; do add "$t" "$key" "$value"; done
  done < <(compgen -e | grep -E "^${prefix}__[A-Za-z_][A-Za-z0-9_]*$" | sort)
done

if [ "$found" = 0 ]; then
  echo "sync-env: no prefixed variables in this environment; nothing written."
  exit 0
fi

for t in web admin specialist; do
  if ! has "$t" NEXT_PUBLIC_SUPABASE_URL && [ -n "${SHARED__SUPABASE_TARGET_URL:-}" ]; then
    add "$t" NEXT_PUBLIC_SUPABASE_URL "$SHARED__SUPABASE_TARGET_URL"
  fi
  if ! has "$t" NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY; then
    if [ -n "${SHARED__SUPABASE_TARGET_PUBLISHABLE_KEY:-}" ]; then
      add "$t" NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY "$SHARED__SUPABASE_TARGET_PUBLISHABLE_KEY"
    elif [ -n "${SHARED__NEXT_PUBLIC_SUPABASE_ANON_KEY:-}" ]; then
      add "$t" NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY "$SHARED__NEXT_PUBLIC_SUPABASE_ANON_KEY"
    fi
  fi
  add "$t" NEXT_PUBLIC_WEB_URL "http://localhost:3000"
  add "$t" NEXT_PUBLIC_ADMIN_URL "http://localhost:3001"
  add "$t" NEXT_PUBLIC_SPECIALIST_URL "http://localhost:3002"
done

umask 077
for t in web admin specialist root; do
  file="${files[$t]}"
  [ -n "${content[$t]:-}" ] || continue
  if [ -f "$file" ] && ! head -n1 "$file" | grep -qF "$header"; then
    echo "sync-env: ${file#"$root"/} was written by hand; left unchanged."
    continue
  fi
  printf '%s\n%s' "$header" "${content[$t]}" > "$file"
  echo "sync-env: wrote ${file#"$root"/} ($(printf '%s' "${content[$t]}" | grep -c '=') variables)"
done
